# Realtional OPerator

# Operator	Name	Description	Example (x = 10, y = 5)	Result
# ==	Equal to	Returns True if both sides are equal	x == y	False
# !=	Not equal to	Returns True if sides are different	x != y	True
# >	Greater than	Returns True if left side is larger	x > y	True
# <	Less than	Returns True if left side is smaller	x < y	False
# >=	Greater than or equal to	Returns True if left is larger or equal	x >= 10	True
# <=	Less than or equal to	Returns True if left is smaller or equal	x <= y	False
